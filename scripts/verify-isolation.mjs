#!/usr/bin/env node
/**
 * Verify the agent isolation boundary against a real container.
 *
 * The unit tests assert what the generated command must contain. This script
 * asserts what the resulting container actually denies, which is the property
 * that matters: a process running as the agent must not be able to read the
 * evaluation package, the manifests, or the host's Docker socket.
 *
 * It materializes a trial, builds the isolated agent container command from the
 * same pure function the unit tests cover, and runs that container with a probe
 * that looks for exactly the things that must be absent. If `docker` is not on
 * PATH — the controller container has no Docker client — it writes the command
 * to run-probe.sh in the trial directory so the compute host can execute it,
 * and reports that it did.
 *
 * Usage: node scripts/verify-isolation.mjs [fixture-root] [--run]
 */
import { spawnSync } from "node:child_process";
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { buildAgentContainer, loadFixture, materializeFixture } from "../packages/controller/src/index.ts";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE_ROOT = process.argv[2] ?? join(REPO_ROOT, "fixtures");
const ALWAYS_RUN = process.argv.includes("--run");
const RUNS_DIR = join(REPO_ROOT, "runs");
const FIXTURE_ID = "control-plane-001";
const TRIAL_ID = "isolation-probe";
const STATE_DIR = join(RUNS_DIR, "agent-state", TRIAL_ID);
const RSIH_DIR = join(REPO_ROOT, "third_party", "RSI-Harness");
const IMAGE = "evocfd-dev:node22";
const PROBE = [
  'set -u',
  'echo "== agent view =="; ls -A /task',
  'echo "== container root =="; ls -A /',
  'echo "== prompt present =="; head -c 32 /task/TASK.md; echo',
  'echo "== harness =="; test -d /rsih && echo rsih-ok || echo BAD-no-rsih',
  'echo "== agent state =="; test -d /agent-state -a -w /agent-state && echo state-writable || echo BAD-state',
  'echo "== workspace writable =="; (touch /task/workspace/.probe && echo workspace-writable) || echo BAD-workspace',
  'echo "== task top level read-only =="; (touch /task/.probe && echo BAD-task-writable) || echo task-readonly-ok',
  'echo "== evaluator =="; (cat /task/../private/evaluator/check.mjs >/dev/null && echo BAD-evaluator-readable) || echo evaluator-unreachable',
  'echo "== manifests =="; (cat /task/../manifests/trial.json >/dev/null && echo BAD-manifests-readable) || echo manifests-unreachable',
  'echo "== docker socket =="; (test -S /var/run/docker.sock && echo BAD-socket-present) || echo socket-absent',
].join("; ");

const BAD_MARKERS = ["BAD-"];

const fixture = await loadFixture(join(FIXTURE_ROOT, FIXTURE_ID));
await mkdir(STATE_DIR, { recursive: true });
const trial = await materializeFixture({ fixture, trialId: TRIAL_ID, runsDir: RUNS_DIR });

const launch = buildAgentContainer(
  { trialRoot: trial.layout.root, rsihDir: RSIH_DIR, agentStateDir: STATE_DIR, uid: 1001, gid: 1001 },
  IMAGE,
);

const argv = ["docker", "run", ...launch.args, "sh", "-c", PROBE];

const shellScript = [
  "#!/bin/sh",
  "# Generated by scripts/verify-isolation.mjs — do not edit.",
  "# Runs the isolated agent container and prints its probe output.",
  "# Any line beginning BAD- means the isolation boundary failed.",
  "",
  `set -u`,
  `exec ${argv.map((a) => `'${a.replaceAll("'", "'\\''")}'`).join(" ")}`,
  "",
].join("\n");
await writeFile(join(trial.layout.root, "run-probe.sh"), shellScript, { mode: 0o755 });

let output;
const docker = spawnSync("docker", argv.slice(1), { encoding: "utf8" });
if (docker.error || docker.status === null) {
  if (ALWAYS_RUN) {
    console.error("docker is required for --run but could not be started");
    process.exitCode = 2;
  } else {
    console.log(`materialized ${TRIAL_ID} at ${trial.layout.root}`);
    console.log("docker client unavailable here — run the probe on the compute host:\n");
    console.log(`  sh ${trial.layout.root}/run-probe.sh\n`);
    console.log("or: node scripts/verify-isolation.mjs --run");
  }
} else {
  output = (docker.stdout ?? "") + (docker.stderr ?? "");
  const failures = output
    .split("\n")
    .filter((line) => BAD_MARKERS.some((marker) => line.includes(marker)));
  console.log(output.trim());
  if (failures.length) {
    console.error(`\nISOLATION FAILED:\n${failures.map((f) => "  " + f).join("\n")}`);
    process.exitCode = 1;
  } else {
    console.log("\nisolation boundary verified: nothing the agent must not see was reachable");
  }
}
